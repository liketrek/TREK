import type {
  BookLockup,
  BookLockupRole,
  BookLockupShapePart,
  BookLockupTextPart,
  BookLockupTone,
} from './book-lockups';

/**
 * The 24 lockups, in the units of a box 100 wide (book-lockups.ts).
 *
 * Type sizes are chosen against the share of the page a lockup takes, so the
 * printed sizes land where the type scale wants them on a 210 mm page: a cover
 * title between 70 and 180 pt, spaced capitals at 8 to 11 pt with a quarter to
 * half an em of tracking, a title at least three times its subtitle. Every
 * frame is a little taller than its line, and the parts never touch unless
 * they are meant to layer, so a lockup placed as it comes has no severe finding.
 *
 * The faces are the book's own (book-fonts.data.ts): condensed and heavy
 * poster faces for titles, Montserrat for spaced capitals, a thin serif and its
 * italic for quiet titles and quotes, a script for the word laid over a title,
 * DM Mono for coordinates.
 */

/** A line of spaced capitals: a date line, a kicker, a year. */
function spaced(
  role: BookLockupRole,
  y: number,
  size: number,
  tone: BookLockupTone = 'muted',
  more: Partial<BookLockupTextPart> = {},
): BookLockupTextPart {
  return {
    kind: 'text',
    role,
    x: 0,
    y,
    w: 100,
    h: size * 2,
    font: 'montserrat',
    size,
    weight: 600,
    tracking: 0.4,
    transform: 'upper',
    tone,
    ...more,
  };
}

/** A filled bar: a rule when it is thin, a band when it is not. */
function bar(x: number, y: number, w: number, h: number, fill: BookLockupTone = 'ink'): BookLockupShapePart {
  return { kind: 'shape', shape: 'rect', x, y, w, h, fill };
}

/** A circle drawn as a line only. */
function ring(inset: number, stroke: BookLockupTone, strokeWidth: number, size = 100): BookLockupShapePart {
  const side = size - inset * 2;
  return { kind: 'shape', shape: 'ellipse', x: inset, y: inset, w: side, h: side, fill: null, stroke, strokeWidth };
}

/** A condensed poster face, Bebas unless the part says another: capitals, tight lines. */
function poster(
  role: BookLockupRole,
  y: number,
  size: number,
  more: Partial<BookLockupTextPart> = {},
): BookLockupTextPart {
  return {
    kind: 'text',
    role,
    x: 0,
    y,
    w: 100,
    h: size * 1.05,
    font: 'bebas',
    size,
    leading: 0.9,
    tracking: 0.02,
    transform: 'upper',
    tone: 'ink',
    ...more,
  };
}

